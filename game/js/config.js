// Ширина поля фиксирована, высота подбирается под пропорции экрана — без чёрных полос на длинных экранах
export const GAME_WIDTH = 720;
export const MIN_GAME_HEIGHT = 1280;   // 16:9 и шире (планшеты) — поля по бокам, вёрстка не сжимается
export const MAX_GAME_HEIGHT = 1800;   // ~22.5:9

export function gameHeightFor(viewWidth, viewHeight) {
    const height = Math.round(GAME_WIDTH * viewHeight / viewWidth);
    return Math.min(MAX_GAME_HEIGHT, Math.max(MIN_GAME_HEIGHT, height));
}

// Раскладка от краёв экрана: сверху HUD, стакан — всё остальное до самого низа (кнопок внизу нет:
// «назад» и «готово» — в HUD, звук — на карте). inset — вырез камеры сверху (px поля, widgets.safeTop).
// HUD стоит на высоте шапки карты: верх стакана — там же, где у карты граница шапки (MAP_HEADER)
export const MAP_HEADER = 272;
// px: воздух над ободком стакана. Гарнир из магазина — предметы в настоящем масштабе (соломинка
// 190 мм, зонтик), им нужно место над кромкой, а до строки «ТРЯСКА» его было 44 px. HUD остаётся
// на месте, вниз едет стакан: он теряет эту высоту, частиц в нём соответственно меньше
export const RIM_HEADROOM = 150;
export function computeLayout(height, inset = 0) {
    const glassTop = Math.max(16, inset) + MAP_HEADER + RIM_HEADROOM;
    // Строки HUD раньше стояли вплотную (4 px между названием и временем, 11 px между временем и полосой).
    // Над ними было ~100 px пустоты — поднимаем верхнюю строку и разводим остальные
    const hudTitleY = Math.max(16, inset) + MAP_HEADER - 214;
    const glassBottom = height - 24;
    return {
        width: GAME_WIDTH,
        height,
        hudTitleY,                       // «Назад», название уровня и цели звёзд
        hudTimerY: hudTitleY + 62,       // Время, очки, процент
        hudProgressY: hudTitleY + 118,
        hudShakeY: hudTitleY + 170,      // Сила тряски и комбо-множитель
        statusY: glassTop + 330,
        glass: { x: 40, y: glassTop, width: 640, height: glassBottom - glassTop, radius: 24 }
    };
}

