// Профиль удара: как жидкость отвечает на встряхивание.
//
// Прогресс уровня считается по встряхиваниям, и до сих пор каждое давало порцию, пропорциональную
// своей силе, — одинаково для любой жидкости. Профиль меняет само правило зачёта, и этим одна
// жидкость отличается от другой в руке, а не только на вид:
//   густую (глицерин, сироп) берут медленные сильные размахи — частая мелкая дробь её почти не мешает;
//   лёгкую (вода, спирт) мешает и слабая частая тряска, а лишняя сила впустую;
//   лёд и газировку (позже) — только резкие одиночные удары.
//
// Профиль — данные, а не код: rate — насыщение по темпу (встряхиваний в секунду, выше которого
// частить бессмысленно; 0 — без предела), power — диапазон силы, в котором удар набирает полный зачёт.
export const STROKE_PROFILES = {
    // Как было до профилей: сила засчитывается как есть, темп не ограничен
    even: { rate: 0, power: [0, 1] },
    // Густая жидкость: насыщение по темпу. Чаще rate раз в секунду трясти бессмысленно —
    // вязкая масса просто не успевает отозваться, лишние рывки уходят впустую. Замер живой руки
    // показал, что «медленно и сильно» у человека выходит слабее дроби и по ускорению (0.58 против
    // 0.93), и по размаху (2.0 против 3.05 м/с), поэтому награждать размах нечем — зато можно
    // убрать смысл в дроби, и тогда густую жидкость мешают спокойно и широко
    // offBeat — сколько даёт встряхивание мимо такта (по умолчанию RHYTHM.offBeat). У густой
    // жидкости ровная тряска и игра в такт почти равны по скорости, и звёзды сходились в одну точку:
    // тут важнее попадать, а не частить
    thick: { rate: 3.3, power: [0.25, 0.8], offBeat: 0.35 },
    // Лёгкая жидкость: отзывается на что угодно, хватает и слабых встряхиваний
    light: { rate: 0, power: [0, 0.75] },
    // Резкие одиночные удары: насыщение раннее, слабые не в счёт
    sharp: { rate: 2.5, power: [0.6, 1] }
};

function ramp(value, [from, to]) {
    if (to <= from) return value <= from ? 1 : 1;
    if (value <= from) return 0;
    if (value >= to) return 1;
    return (value - from) / (to - from);
}

// Доля порции за одно встряхивание: 1 — как полноценное, 0 — не засчитано.
// gap — промежуток с прошлого встряхивания: при насыщении удар, пришедший раньше срока,
// засчитывается ровно настолько, насколько успел «созреть»
export function strokeScore(profile, power, gap) {
    const p = profile || STROKE_PROFILES.even;
    const byPower = p.power[1] <= p.power[0] ? power : ramp(power, p.power);
    const byRate = p.rate > 0 ? Math.min(1, gap * p.rate) : 1;
    return byPower * byRate;
}

// Счётчик по кадрам: помнит время последнего встряхивания, чтобы знать промежуток
export class StrokeMeter {
    constructor(profile) {
        this.profile = STROKE_PROFILES[profile] || STROKE_PROFILES.even;
        this.last = -Infinity;
    }

    // frame — то, что отдал детектор (strokes, strokePowers, strokeTimes).
    // Возвращает суммарную долю порции за кадр
    consume(frame) {
        let sum = 0;
        for (let i = 0; i < frame.strokes; i++) {
            const time = frame.strokeTimes[i];
            const gap = time - this.last;
            sum += strokeScore(this.profile, frame.strokePowers[i], gap);
            this.last = time;
        }
        return sum;
    }

    reset() {
        this.last = -Infinity;
    }
}
