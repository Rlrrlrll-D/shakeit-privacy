// Генератор псевдослучайных чисел с зерном (mulberry32): одно зерно — одна и та же последовательность.
// Нужен для честных рекордов: одинаковая раскладка и "случайность" в каждом заезде,
// результат зависит только от тряски игрока
export function createRng(seed) {
    let s = seed >>> 0;
    return function rng() {
        s = (s + 0x6D2B79F5) >>> 0;
        let t = s;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}
